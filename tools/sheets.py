#!/usr/bin/env python3
"""Preflight the design sheets and generate mod/eldenops/src/sheets.rs from them.

    python3 tools/sheets.py preflight   # list unfilled cells and unresolved references
    python3 tools/sheets.py gen         # preflight, then write sheets.rs
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DESIGN = ROOT / "design"
OUT = ROOT / "mod" / "eldenops" / "src" / "sheets.rs"
OUT_SETUP = ROOT / "mod" / "eldenops-setup" / "src" / "aliases.rs"

# (sheet, column) -> sheet whose ids the cell must reference
REFS = {
    ("perks", "jingle_sound"): "sounds",
    ("perks", "sting_sound"): "sounds",
    ("perks", "hook"): "hooks",
    ("systems", "rules"): "round_rules",
    ("systems", "sounds"): "sounds",
    ("systems", "hooks"): "hooks",
    ("round_rules", "used_by"): "systems",
}


def load():
    sheets = {}
    for p in sorted(DESIGN.glob("*.json")):
        s = json.loads(p.read_text(encoding="utf-8"))
        sheets[s["sheet"]] = s
    return sheets


def preflight(sheets):
    problems = []
    ids = {name: {r["id"] for r in s["rows"]} for name, s in sheets.items()}
    for name, s in sheets.items():
        seen = set()
        for i, row in enumerate(s["rows"]):
            rid = row.get("id", f"#{i}")
            if rid in seen:
                problems.append(f"{name}.{rid}: duplicate id")
            seen.add(rid)
            for col in s["columns"]:
                if col not in row or row[col] is None or row[col] == "":
                    problems.append(f"{name}.{rid}.{col}: unfilled")
                    continue
                target = REFS.get((name, col))
                if target:
                    vals = row[col] if isinstance(row[col], list) else [row[col]]
                    for v in vals:
                        if v not in ids.get(target, set()):
                            problems.append(f"{name}.{rid}.{col}: '{v}' is not a row of {target}")
            for col in row:
                if col not in s["columns"]:
                    problems.append(f"{name}.{rid}.{col}: column not declared")
    # every sound is used by a perk or a system; every hook by something
    used_sounds = {r[c] for r in sheets["perks"]["rows"] for c in ("jingle_sound", "sting_sound")}
    used_sounds |= {x for r in sheets["systems"]["rows"] for x in r["sounds"]}
    for sid in ids["sounds"] - used_sounds:
        problems.append(f"sounds.{sid}: not used by any perk or system")
    used_hooks = {r["hook"] for r in sheets["perks"]["rows"]} | {x for r in sheets["systems"]["rows"] for x in r["hooks"]}
    for hid in ids["hooks"] - used_hooks:
        problems.append(f"hooks.{hid}: not used by any perk or system")
    return problems


def rs_str(v):
    return json.dumps(v, ensure_ascii=False)


def rs_f32(v):
    s = repr(float(v))
    return s if "." in s or "e" in s else s + ".0"


def gen(sheets):
    rules = {r["id"]: r for r in sheets["round_rules"]["rows"]}
    L = ["// @generated by tools/sheets.py from design/*.json. Edit the sheets, not this file.", "#![allow(dead_code)]", ""]
    L.append("// round_rules")
    for rid, r in rules.items():
        v = r["value"]
        name = rid.upper()
        if isinstance(v, float):
            L.append(f"pub const {name}: f32 = {rs_f32(v)}; // {r['unit']} ({r['bo2_source']})")
        else:
            L.append(f"pub const {name}: i32 = {v}; // {r['unit']} ({r['bo2_source']})")
    L.append("")
    L.append("// scoring")
    for r in sheets["scoring"]["rows"]:
        L.append(f"pub const {r['id'].upper()}: i32 = {r['points']}; // {r['bo2_source']}")
    L.append("")
    sounds = sheets["sounds"]["rows"]
    L.append("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]")
    L.append("pub enum Snd {")
    snd_variant = {}
    for r in sounds:
        v = "".join(p.capitalize() for p in r["id"].removeprefix("snd_").split("_"))
        snd_variant[r["id"]] = v
        L.append(f"    {v},")
    L.append("}")
    L.append("")
    L.append("pub struct SoundRow { pub snd: Snd, pub bo2_alias: &'static str, pub volume: f32, pub required: bool }")
    L.append("pub const SOUNDS: &[SoundRow] = &[")
    for r in sounds:
        L.append(f"    SoundRow {{ snd: Snd::{snd_variant[r['id']]}, bo2_alias: {rs_str(r['bo2_alias'])}, volume: {rs_f32(r['volume'])}, required: {str(r['required']).lower()} }},")
    L.append("];")
    L.append("")
    L.append("#[derive(Clone, Copy, Debug, PartialEq, Eq)]")
    L.append("pub enum PerkEffect { BonusHealthPoolOfMax, StaminaRegenPerSecondOfMax, DamageDealtMultiplier, SelfReviveFullHpOnce }")
    effects = {
        "bonus_health_pool_of_max": "BonusHealthPoolOfMax",
        "stamina_regen_per_second_of_max": "StaminaRegenPerSecondOfMax",
        "damage_dealt_multiplier": "DamageDealtMultiplier",
        "self_revive_full_hp_once": "SelfReviveFullHpOnce",
    }
    L.append("pub struct PerkRow { pub id: &'static str, pub name: &'static str, pub cost: i32, pub key: &'static str, pub key_vk: i32, pub jingle: Snd, pub sting: Snd, pub effect: PerkEffect, pub effect_value: f32 }")
    L.append("pub const PERKS: &[PerkRow] = &[")
    for r in sheets["perks"]["rows"]:
        L.append(
            f"    PerkRow {{ id: {rs_str(r['id'])}, name: {rs_str(r['name'])}, cost: {r['cost']}, key: {rs_str(r['key'])}, key_vk: {r['key_vk']}, "
            f"jingle: Snd::{snd_variant[r['jingle_sound']]}, sting: Snd::{snd_variant[r['sting_sound']]}, effect: PerkEffect::{effects[r['effect']]}, effect_value: {rs_f32(r['effect_value'])} }},"
        )
    L.append("];")
    L.append("")
    L.append("#[derive(Clone, Copy, Debug, PartialEq, Eq)]")
    L.append("pub enum Anchor { BottomLeft, BottomRight, TopCenter }")
    anchors = {"bottom_left": "BottomLeft", "bottom_right": "BottomRight", "top_center": "TopCenter"}
    L.append("pub struct HudRow { pub anchor: Anchor, pub offset: [f32; 2], pub font_px: f32, pub color: [f32; 4] }")
    for r in sheets["hud"]["rows"]:
        c = ", ".join(rs_f32(x) for x in r["color_rgba"])
        L.append(f"pub const {r['id'].upper()}: HudRow = HudRow {{ anchor: Anchor::{anchors[r['anchor']]}, offset: [{rs_f32(r['offset_x'])}, {rs_f32(r['offset_y'])}], font_px: {rs_f32(r['font_px'])}, color: [{c}] }};")
    L.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    A = ["// @generated by tools/sheets.py from design/sounds.json. Edit the sheet, not this file.", "pub const ALIASES: &[&str] = &["]
    A += [f"    {rs_str(r['bo2_alias'])}," for r in sounds]
    A += ["];", ""]
    OUT_SETUP.write_text("\n".join(A), encoding="utf-8")
    print(f"wrote {OUT_SETUP.relative_to(ROOT)}")


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "preflight"
    sheets = load()
    problems = preflight(sheets)
    total = sum(len(s["rows"]) * len(s["columns"]) for s in sheets.values())
    print(f"preflight: {len(sheets)} sheets, {sum(len(s['rows']) for s in sheets.values())} rows, {total} cells checked")
    for p in problems:
        print("  ✗", p)
    if problems:
        print(f"{len(problems)} problem(s): fix the sheets before building")
        sys.exit(1)
    print("preflight clean")
    if cmd == "gen":
        gen(sheets)


if __name__ == "__main__":
    main()
